"""Rebuild correct scheme files for three defective catalogue formats and verify them.

  python3 make_fixes.py        downloads what it needs into data/fixes/, writes the rebuilt files there and
                               results/FIXES.md (verdicts, triad counts, sha256 of every input and output).

The rebuilt files are derived from the catalogue's own files, so they are not published in this repository;
make_fixes.py regenerates them from the catalogue.
  11x25x28  the served tensor file is truncated; the same format's LRP file is complete, and is converted.
  15x20x26  serendipitous product (A. I. Perminov, arXiv:2606.02480) with every U-bud the served outer scheme has.
  8x27x30   plain tensor product <4x9x10:250> (x) <2x3x3:15> (the served outer scheme has no V-buds).
Also checks, exactly on random inputs, the raw programs (_raw.mpl) served for these three formats."""
import os, sys, json, subprocess, hashlib, urllib.request, time
W = os.path.dirname(os.path.abspath(__file__)); F = W + '/data/fixes'; os.makedirs(F, exist_ok=True)
sys.path.insert(0, W); sys.path.insert(0, W + '/tools')
def get(name):
    p = F + '/' + name
    if not os.path.exists(p):
        with urllib.request.urlopen('https://fmm.univ-lille.fr/' + name, timeout=300) as r: open(p, 'wb').write(r.read())
    return p
sha = lambda p: hashlib.sha256(open(p, 'rb').read()).hexdigest()
def sh(*args): return subprocess.run([sys.executable] + list(args), cwd=F, capture_output=True, text=True, check=True).stdout
inputs = ['11x25x28_tensor.mpl.bz2', '11x25x28_LRP.mpl.bz2'] + ['%s_raw.mpl.bz2' % f for f in ('11x25x28', '15x20x26', '8x27x30')] + \
         ['%s_tensor.mpl.bz2' % f for f in ('5x5x13', '2x3x4', '3x4x6', '3x4x4', '4x9x10', '2x3x3')]
for n in inputs: get(n)
log = ['# Rebuilt files (generated by make_fixes.py)\n', 'Inputs, downloaded from fmm.univ-lille.fr into data/fixes/ on %s (make_fixes.py reuses files already there):\n' % time.strftime('%Y-%m-%d', time.localtime(min(os.path.getmtime(F + '/' + n) for n in inputs))),
       '| file | sha256 |', '|---|---|'] + ['| %s | `%s` |' % (n, sha(F + '/' + n)) for n in inputs] + ['']
# 11x25x28 from its LRP file
probe = sh(W + '/tools/lrp_probe.py', '11x25x28')
best = min((l.split() for l in probe.splitlines() if l.startswith('11x25x28 ') and 'AB' in l), key=lambda t: float(t[-1]))
conv = ''.join(best[1:4])
sh(W + '/tools/lrp_to_tensor.py', '11', '25', '28', '11x25x28_LRP.mpl.bz2', '11x25x28_rebuilt_raw.mpl.bz2', conv)
from construct import load, orient, build, mat as cmat
from catfmt import write_full
import bz2, re
def finish(scheme_or_path, X, Y, Z, out):
    if isinstance(scheme_or_path, str):
        body = bz2.open(F + '/' + scheme_or_path, 'rt').read(); inner = body[body.find('TriadSet([') + 10: body.rfind(']):')]
        trs = re.findall(r'Triad\(\[.*?\]\)\]\)', inner)
    else:
        trs = ['Triad([%s, %s, %s])' % tuple(cmat(M) for M in t) for t in scheme_or_path]
    write_full(F + '/' + out, X, Y, Z, trs); return F + '/' + out
outs = [('11x25x28', 4572, finish('11x25x28_rebuilt_raw.mpl.bz2', 11, 25, 28, '11x25x28_tensor_rebuilt.mpl.bz2'),
         'LRP file converted (vec convention %s found by tools/lrp_probe.py)' % conv)]
g = lambda n, *d: orient(load(F + '/%s_tensor.mpl.bz2' % n), *d)
outs.append(('15x20x26', 4464, finish(build(g('5x5x13', 5, 5, 13), g('2x3x4', 3, 4, 2), [(3, 'U', 6, g('3x4x6', 3, 4, 6)), (2, 'U', 19, g('3x4x4', 3, 4, 4))]), 15, 20, 26, '15x20x26_tensor_rebuilt.mpl.bz2'),
             'serendipitous product with the 6 U-bud triples and 19 U-bud pairs of the served 5x5x13:227 (the stated recipe needs 4 triples and 26 pairs)'))
outs.append(('8x27x30', 3744, finish(build(g('4x9x10', 4, 9, 10), g('2x3x3', 2, 3, 3), []), 8, 27, 30, '8x27x30_tensor_rebuilt.mpl.bz2'),
             'tensor product <4x9x10:250> (x) <2x3x3:15>; the served 4x9x10:250 has no V-buds, so the stated <4,3,3> blocks are not available'))
from verify_fmm import verify
log += ['| format | stated rank | rebuilt triads | verify_fmm.py | randeval.py (A.B wrong entries) | how | sha256 of rebuilt file |', '|---|---|---|---|---|---|---|']
for fmt, stated, path, how in outs:
    X, Y, Z = map(int, fmt.split('x')); r = verify(path, X, Y, Z, stated)
    ev = json.loads(subprocess.run([sys.executable, W + '/randeval.py', path, str(X), str(Y), str(Z)], capture_output=True, text=True).stdout.strip().splitlines()[-1])
    log.append('| %s | %d | %s | %s | %d of %d | %s | `%s` |' % (fmt, stated, r.get('rank'), r['verdict'], ev['wrong'], ev['entries'], how, sha(path)))
    print(fmt, r['verdict'], r.get('rank'), ev['wrong'], flush=True)
log += ['', 'Raw programs served for the same formats (tools/raw_probe.py, exact, random A, B and parameter values):', '']
for fmt in ('11x25x28', '15x20x26', '8x27x30'):
    log.append('- ' + sh(W + '/tools/raw_probe.py', fmt).strip())
# 11x25x28: compare with the truncated served file
a = bz2.open(F + '/11x25x28_tensor.mpl.bz2', 'rt').read(); b = bz2.open(outs[0][2], 'rt').read()
seg = lambda t: [x.rstrip(', ') for x in re.sub(r'\s+', '', t[t.find('TriadSet'):]).split('Triad([')[1:]]
ta, tb = seg(a), seg(b)
complete = ta[:-1]                                   # the last segment of the truncated file is cut off
same = 0
for x, y in zip(complete, tb):
    if x == y: same += 1
    else: break
prefix_ok = tb[len(complete)].startswith(ta[-1])
log += ['', '11x25x28: the truncated served file holds %d complete triads and part of one more. The first %d triads of the rebuilt file are identical to them, character for character (whitespace removed), and the cut-off text is a prefix of the rebuilt file\'s next triad: %s.' % (len(complete), same, prefix_ok)]
open(W + '/results/FIXES.md', 'w').write('\n'.join(log) + '\n'); print('\n'.join(log[-6:]))
